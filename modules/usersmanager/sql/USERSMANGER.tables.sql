-- Occupation du stockage par application
CREATE VIEW [dbo].[vw_storage_by_app] AS
SELECT
    APPCODE,
    COUNT(*)                                    AS TotalFiles,
    SUM(SIZEBYTES) / 1048576.0                  AS TotalStoredMB,
    SUM(ORIGINALSIZEBYTES) / 1048576.0          AS TotalOriginalMB,
    SUM(ORIGINALSIZEBYTES - SIZEBYTES) / 1048576.0 AS SavedMB,
    ROUND(
        100.0 * (1 - SUM(SIZEBYTES) * 1.0 / NULLIF(SUM(ORIGINALSIZEBYTES), 0)),
        2
    )                                           AS CompressionRatePct
FROM Attachments
WHERE DELETEDAT IS NULL AND STATUS = 'READY'
GROUP BY APPCODE;

