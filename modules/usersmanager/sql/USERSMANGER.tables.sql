    ug.GRPID IS NOT NULL
    OR g.GRPBAS = 1;

CREATE INDEX ix_ug_usrid ON #UserGroups(USRID);
-- Pré-agrégation JSON des groupes par utilisateur
DROP TABLE IF EXISTS #GroupsJSON;
SELECT
