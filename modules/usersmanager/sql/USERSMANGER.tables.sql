CREATE VIEW [dbo].[V_UserPermissions]
AS
/* Permissions directes*/
SELECT
    u.USRID,
    u.FSTNAM + ' ' + u.LSTNAM AS FLLNAM,
    a.APPID,
    a.APPCOD,
    a.APPNAM,
    a.APPDES,
    a.ACTIVE AS APPACTV,
	a.APPLNK,
    a.IMGLNK,
    a.LOGLNK,
    a.DOCLNK,
    p.PRMID,
    p.PRMNAM,
    p.PRMDES,
    p.PRMLVL,
    p.ISCRIT,
    'DIRECT' AS SRC,
    NULL AS GRPID,
    NULL AS GRPNAM,
    NULL AS GRPDES,
    NULL AS GRPACTV
FROM
    USERS u
    JOIN PRMUSR pu ON u.USRID = pu.USRID
    JOIN APPLICATIONS a ON pu.APPID = a.APPID
    JOIN PERMISSIONS p ON pu.PRMID = p.PRMID
UNION
/* Permissions via groupes (groupes directs + groupes globaux uniques) */
SELECT
    u.USRID,
    u.FSTNAM + ' ' + u.LSTNAM AS FLLNAM,
    a.APPID,
    a.APPCOD,
    a.APPNAM,
    a.APPDES,
    a.ACTIVE AS APPACTV,
	a.APPLNK,
    a.IMGLNK,
    a.LOGLNK,
    a.DOCLNK,
    p.PRMID,
    p.PRMNAM,
    p.PRMDES,
    p.PRMLVL,
    p.ISCRIT,
    'GROUP' AS SRC,
    g.GRPID,
    g.GRPNAM,
    g.GRPDES,
    g.ACTIVE AS GRPACTV
FROM
    USERS u
    JOIN USRGRP ug ON u.USRID = ug.USRID
    JOIN GROUPS g ON g.GRPID = ug.GRPID
    JOIN PRMGRP pg ON g.GRPID = pg.GRPID
    JOIN APPLICATIONS a ON pg.APPID = a.APPID
    JOIN PERMISSIONS p ON pg.PRMID = p.PRMID
UNION
SELECT
    u.USRID,
    u.FSTNAM + ' ' + u.LSTNAM AS FLLNAM,
    a.APPID,
    a.APPCOD,
    a.APPNAM,
    a.APPDES,
    a.ACTIVE AS APPACTV,
	a.APPLNK,
    a.IMGLNK,
    a.LOGLNK,
    a.DOCLNK,
    p.PRMID,
    p.PRMNAM,
    p.PRMDES,
    p.PRMLVL,
    p.ISCRIT,
    'GROUP' AS SRC,
    g.GRPID,
    g.GRPNAM,
    g.GRPDES,
    g.ACTIVE AS GRPACTV
FROM
    USERS u
    JOIN GROUPS g ON g.GRPBAS = 1
    LEFT JOIN USRGRP ug ON u.USRID = ug.USRID
    AND g.GRPID = ug.GRPID
    JOIN PRMGRP pg ON g.GRPID = pg.GRPID
    JOIN APPLICATIONS a ON pg.APPID = a.APPID
    JOIN PERMISSIONS p ON pg.PRMID = p.PRMID
WHERE
    ug.GRPID IS NULL
    AND g.ACTIVE = 1
